import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  captionWorkbookFilename,
  readCaptionMap,
  sortedPortraitFilenames,
  titleFromName
} from "./portrait-caption-xlsx.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const portraitDir = path.join(root, "public", "assets", "portrait");
const outPath = path.join(root, "src", "portrait-gallery.js");

const captions = readCaptionMap(path.join(portraitDir, captionWorkbookFilename));
const files = sortedPortraitFilenames(portraitDir);

const entries = files.map((name) => {
  const captionRow = captions.get(name) || {};
  const fallbackTitle = titleFromName(name);
  const displayTitle = captionRow.displayTitle || captionRow.captionContext || fallbackTitle;
  const caption = captionRow.displayTitle ? captionRow.captionContext || "" : "";

  return {
    filename: name,
    title: displayTitle,
    src: `/assets/portrait/${encodeURIComponent(name).replace(/%2F/g, "/")}`,
    alt: `Jonathan Yu portrait photo: ${displayTitle}`,
    caption
  };
});

const source = `// Generated by scripts/sync-portrait-gallery.mjs from public/assets/portrait.
const portraitGallery = ${JSON.stringify(entries, null, 2)};

export default portraitGallery;
`;

fs.writeFileSync(outPath, source);
console.log(`Wrote ${outPath}`);
console.log(`Portrait photos: ${entries.length}`);
