import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const portraitDir = path.join(root, "public", "assets", "portrait");
const outPath = path.join(root, "src", "portrait-gallery.js");
const imagePattern = /\.(jpe?g|png|webp|gif)$/i;
const headerOnlyFile = "jonathan-yu-headshot.jpg";
const originalHeaderFile = "received_408407423126180.jpeg";

function titleFromName(name) {
  const base = path.basename(name, path.extname(name));
  if (name === headerOnlyFile) return "Jonathan Yu headshot";
  if (name === originalHeaderFile) return "Original profile photo";

  return base
    .replace(/[_-]+/g, " ")
    .replace(/\s+/g, " ")
    .trim()
    .replace(/\b\w/g, (letter) => letter.toUpperCase());
}

const files = fs
  .readdirSync(portraitDir, { withFileTypes: true })
  .filter((entry) => entry.isFile() && imagePattern.test(entry.name))
  .map((entry) => entry.name)
  .sort((a, b) => {
    if (a === headerOnlyFile) return -1;
    if (b === headerOnlyFile) return 1;
    if (a === originalHeaderFile) return -1;
    if (b === originalHeaderFile) return 1;
    return a.localeCompare(b, undefined, { numeric: true, sensitivity: "base" });
  });

const entries = files.map((name) => ({
  filename: name,
  title: titleFromName(name),
  src: `/assets/portrait/${encodeURIComponent(name).replace(/%2F/g, "/")}`,
  alt: `Jonathan Yu portrait photo: ${titleFromName(name)}`,
  caption: ""
}));

const source = `// Generated by scripts/sync-portrait-gallery.mjs from public/assets/portrait.
const portraitGallery = ${JSON.stringify(entries, null, 2)};

export default portraitGallery;
`;

fs.writeFileSync(outPath, source);
console.log(`Wrote ${outPath}`);
console.log(`Portrait photos: ${entries.length}`);
